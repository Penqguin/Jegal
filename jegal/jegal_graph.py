import json
import os
import asyncio
import pandas as pd
import warnings
from dotenv import load_dotenv
from langgraph.graph import StateGraph, END
import jegal
from jegal.research_agents import NewsScannerAgent, FinancialResearchAgent, EarningsReviewerAgent
from jegal.engine_bridge import write_target_weights

